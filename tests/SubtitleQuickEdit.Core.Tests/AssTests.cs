public class AssTests
{
    // Styles, a Comment line, override tags, a drawing, signs that overlap, out-of-order lines, a [Fonts] section and
    // a section after [Events]: everything the editor must leave alone except the Text it is asked to change.
    private const string Rich =
        "[Script Info]\n"
        + "; Script generated by a test\n"
        + "Title: Test\n"
        + "ScriptType: v4.00+\n"
        + "PlayResX: 1920\n"
        + "\n"
        + "[V4+ Styles]\n"
        + "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding\n"
        + "Style: Default,Arial,48,&H00FFFFFF,&H000000FF,&H00000000,&H00000000,0,0,0,0,100,100,0,0,1,2,1,2,10,10,10,1\n"
        + "Style: Sign,Arial,36,&H00FFFFFF,&H000000FF,&H00000000,&H00000000,0,0,0,0,100,100,0,0,1,2,1,8,10,10,10,1\n"
        + "\n"
        + "[Events]\n"
        + "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n"
        + "Comment: 0,0:00:00.00,0:00:01.00,Default,,0,0,0,,Translator note\n"
        + "Dialogue: 0,0:00:01.00,0:00:03.50,Default,Anna,0,0,0,,{\\an8}Hello, there.\n"
        + "Dialogue: 0,0:00:04.00,0:00:06.00,Default,,0,0,0,,Two lines\\Nin one cue, with {\\i1}italics{\\i0}\n"
        + "Dialogue: 1,0:00:04.50,0:00:05.50,Sign,,0,0,0,,{\\pos(960,100)}SHOP\n"
        + "Dialogue: 0,0:00:05.00,0:00:05.80,Sign,,0,0,0,,{\\p1}m 0 0 l 100 0 100 100{\\p0}\n"
        + "Dialogue: 0,0:00:02.00,0:00:02.90,Default,,0,0,0,Banner;10,Out of order\n"
        + "\n"
        + "[Fonts]\n"
        + "fontname: test.ttf\n"
        + "!!!!$-!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!\n";

    private const string Ssa =
        "[Script Info]\n"
        + "ScriptType: v4.00\n"
        + "\n"
        + "[Events]\n"
        + "Format: Marked, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n"
        + "Dialogue: Marked=0,0:00:01.00,0:00:02.00,Default,,0000,0000,0000,,Old style line\n";

    public static IEnumerable<object[]> Files()
    {
        yield return new object[] { "rich-lf", Fixtures.Utf8(Rich) };
        yield return new object[] { "rich-crlf-bom", Fixtures.Utf8(Rich.Replace("\n", "\r\n", StringComparison.Ordinal), bom: true) };
        yield return new object[] { "no-final-newline", Fixtures.Utf8(Rich.TrimEnd('\n')) };
        yield return new object[] { "ssa", Fixtures.Utf8(Ssa) };
        yield return new object[] { "utf16", Fixtures.Utf16Le(Ssa.Replace("Old style line", "Grüß dich", StringComparison.Ordinal)) };
    }

    [Theory]
    [MemberData(nameof(Files))]
    public void Files_round_trip_byte_for_byte_and_with_an_unchanged_edit(string name, byte[] data)
    {
        AssDocument doc = Parse(data, name);

        Assert.Equal(data, doc.Apply(Array.Empty<SubtitleEdit>()).Content.ToArray());
        SubtitleCue first = doc.Cues[0];
        Assert.Equal(data, doc.Apply(new SubtitleEdit[] { new SubtitleTextEdit(1, first.Text, first.Text) }).Content.ToArray());
    }

    [Fact]
    public void Cues_are_the_dialogue_lines_in_file_order_with_style_and_drawings_read_only()
    {
        AssDocument doc = Parse(Fixtures.Utf8(Rich));

        Assert.Equal(SubtitleFormat.Ass, doc.Format);
        Assert.Equal(
            new[]
            {
                (1, 1000L, 3500L, "{\\an8}Hello, there.", "Default", false),
                (2, 4000L, 6000L, "Two lines\nin one cue, with {\\i1}italics{\\i0}", "Default", false),
                (3, 4500L, 5500L, "{\\pos(960,100)}SHOP", "Sign", false),
                (4, 5000L, 5800L, "{\\p1}m 0 0 l 100 0 100 100{\\p0}", "Sign", true),
                (5, 2000L, 2900L, "Out of order", "Default", false),
            },
            doc.Cues.Select(c => (c.Position, c.StartMs, c.EndMs, c.Text, c.Style ?? string.Empty, c.ReadOnly)).ToArray());
    }

    [Theory]
    [InlineData("\n")]
    [InlineData("\r\n")]
    public void A_text_edit_changes_only_the_text_field_and_line_breaks_become_backslash_n(string eol)
    {
        AssDocument doc = Parse(Fixtures.Utf8(Rich.Replace("\n", eol, StringComparison.Ordinal)));

        byte[] edited = doc.Apply(new SubtitleEdit[]
        {
            new SubtitleTextEdit(2, "Two lines\nin one cue, with {\\i1}italics{\\i0}", "Fixed, still\ntwo {\\i1}lines{\\i0}"),
            new SubtitleTextEdit(1, "{\\an8}Hello, there.", "{\\an8}Hi, there."),
        }).Content.ToArray();

        string expected = Rich
            .Replace("Two lines\\Nin one cue, with {\\i1}italics{\\i0}", "Fixed, still\\Ntwo {\\i1}lines{\\i0}", StringComparison.Ordinal)
            .Replace("{\\an8}Hello, there.", "{\\an8}Hi, there.", StringComparison.Ordinal);
        Assert.Equal(expected.Replace("\n", eol, StringComparison.Ordinal), Encoding.UTF8.GetString(edited));
    }

    [Fact]
    public void An_added_line_copies_the_fields_of_the_line_it_follows_and_rounds_to_centiseconds()
    {
        AssDocument doc = Parse(Fixtures.Utf8(Rich));

        SubtitleApplyResult result = doc.Apply(new SubtitleEdit[] { new SubtitleAddCue("a1", 4504, 5996, "New\nsign") });

        string expected = Rich.Replace(
            "{\\pos(960,100)}SHOP\n",
            "{\\pos(960,100)}SHOP\nDialogue: 1,0:00:04.50,0:00:06.00,Sign,,0,0,0,,New\\Nsign\n",
            StringComparison.Ordinal);
        Assert.Equal(expected, Encoding.UTF8.GetString(result.Content.ToArray()));
        Assert.Equal(4, result.AddedCuePositions["a1"]);
        SubtitleCue added = Parse(result.Content.ToArray()).Cues[3];
        Assert.Equal((4500L, 6000L, "New\nsign", "Sign"), (added.StartMs, added.EndMs, added.Text, added.Style ?? string.Empty));
    }

    [Fact]
    public void Added_lines_go_after_the_line_starting_closest_before_them_or_before_the_first()
    {
        AssDocument doc = Parse(Fixtures.Utf8(Rich));

        SubtitleApplyResult result = doc.Apply(new SubtitleEdit[]
        {
            new SubtitleAddCue("late", 9000, 9500, "Late"),
            new SubtitleAddCue("early", 200, 600, "Early"),
            new SubtitleTextEdit(5, "Out of order", "Still out of order"),
        });

        string text = Encoding.UTF8.GetString(result.Content.ToArray());
        Assert.Contains(
            "Translator note\nDialogue: 0,0:00:00.20,0:00:00.60,Default,Anna,0,0,0,,Early\nDialogue: 0,0:00:01.00",
            text,
            StringComparison.Ordinal);
        Assert.Contains("{\\p0}\nDialogue: 0,0:00:09.00,0:00:09.50,Sign,,0,0,0,,Late\nDialogue: 0,0:00:02.00", text, StringComparison.Ordinal);
        Assert.Contains("Banner;10,Still out of order\n\n[Fonts]", text, StringComparison.Ordinal);
        Assert.Equal(1, result.AddedCuePositions["early"]);
        Assert.Equal(6, result.AddedCuePositions["late"]);
        Assert.Equal(new[] { 7 }, result.EditedCuePositions);
    }

    [Fact]
    public void An_added_line_after_a_last_line_without_a_newline_starts_a_new_line()
    {
        AssDocument doc = Parse(Fixtures.Utf8(Ssa.TrimEnd('\n')));

        byte[] edited = doc.Apply(new SubtitleEdit[] { new SubtitleAddCue("a", 3000, 4000, "Added") }).Content.ToArray();

        Assert.Equal(Ssa + "Dialogue: Marked=0,0:00:03.00,0:00:04.00,Default,,0000,0000,0000,,Added", Encoding.UTF8.GetString(edited));
    }

    [Fact]
    public void Drawings_cannot_be_edited_and_shared_rules_apply()
    {
        AssDocument doc = Parse(Fixtures.Utf8(Rich));

        SubtitleEditException drawing = Refusal(doc, new SubtitleTextEdit(4, "{\\p1}m 0 0 l 100 0 100 100{\\p0}", "x"));
        Assert.Equal((SubtitleEditError.InvalidEdit, 4), (drawing.Error, drawing.CuePosition));
        Assert.Equal(SubtitleEditError.TextMismatch, Refusal(doc, new SubtitleTextEdit(5, "Other", "b")).Error);
        Assert.Equal(SubtitleEditError.CueNotFound, Refusal(doc, new SubtitleTextEdit(6, "x", "b")).Error);
        Assert.Equal(SubtitleEditError.InvalidEdit, Refusal(doc, new SubtitleTextEdit(5, "Out of order", string.Empty)).Error);
        Assert.Equal(SubtitleEditError.InvalidEdit, Refusal(doc, new SubtitleTextEdit(5, "Out of order", "a\u0001b")).Error);
        Assert.Equal("c1", Refusal(doc, new SubtitleAddCue("c1", 1000, 1050, "x")).ClientId);
    }

    [Fact]
    public void Blank_lines_and_commas_are_fine_in_ass_text()
    {
        AssDocument doc = Parse(Fixtures.Utf8(Rich));

        byte[] edited = doc.Apply(new SubtitleEdit[] { new SubtitleTextEdit(5, "Out of order", "a,\n\nb") }).Content.ToArray();

        Assert.Contains("Banner;10,a,\\N\\Nb\n", Encoding.UTF8.GetString(edited), StringComparison.Ordinal);
    }

    [Theory]
    [InlineData("[Events]\nDialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,x\n", "Script Info")]
    [InlineData("[Script Info]\n\n[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\nComment: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,x\n", "no Dialogue")]
    [InlineData("[Script Info]\n\n[Events]\nFormat: Layer, Start, End, Text, Style\nDialogue: 0,0:00:01.00,0:00:02.00,x,Default\n", "end with Text")]
    [InlineData("[Script Info]\n\n[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\nDialogue: 0,0:00:01.00,0:00:02.00\n", "fewer fields")]
    [InlineData("[Script Info]\n\n[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\nDialogue: 0,soon,0:00:02.00,Default,,0,0,0,,x\n", "time")]
    public void Files_that_cannot_be_read_reliably_are_not_editable(string content, string reason)
    {
        AssParseResult result = AssDocument.Parse(Fixtures.Utf8(content));

        Assert.Null(result.Document);
        Assert.Contains(reason, result.FailureReason, StringComparison.Ordinal);
    }

    [Fact]
    public void Without_a_format_line_the_ass_default_is_used()
    {
        AssDocument doc = Parse(Fixtures.Utf8("[Script Info]\n\n[Events]\nDialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,No format\n"));

        Assert.Equal(("No format", "Default", 1000L), (doc.Cues[0].Text, doc.Cues[0].Style ?? string.Empty, doc.Cues[0].StartMs));
    }

    private static SubtitleEditException Refusal(AssDocument doc, SubtitleEdit edit) =>
        Assert.Throws<SubtitleEditException>(() => doc.Apply(new[] { edit }));

    private static AssDocument Parse(byte[] data, string name = "file")
    {
        AssParseResult result = AssDocument.Parse(data);
        Assert.True(result.Document is not null, name + ": " + result.FailureReason);
        return result.Document!;
    }
}
